/*
 * Regenerates src/data/stations.js from NOAA's station metadata API.
 *
 * Run by hand when the station list needs refreshing:
 *   node scripts/update-stations.js
 *
 * Only reference stations (type "R") are kept. Subordinate stations ("S") are
 * excluded on purpose: they serve no 6-minute prediction series, only high/low,
 * and they are mostly back-bay and creek gauges whose tides differ sharply from
 * the open coast a short distance away. Including them would put a station
 * closer to most queries while making the answer worse.
 */

const fs = require('fs');
const path = require('path');

const MDAPI_URL = 'https://api.tidesandcurrents.noaa.gov/mdapi/prod/webapi/stations.json?type=tidepredictions';
const OUTPUT_PATH = path.join(__dirname, '..', 'src', 'data', 'stations.js');

// NOAA hands back coordinates with more digits than a double represents exactly,
// which is false precision and trips no-loss-of-precision on the generated file.
// 5dp is a little over a metre - far finer than picking a station needs.
const COORDINATE_DECIMALS = 5;
const roundCoordinate = value => Number(Number(value).toFixed(COORDINATE_DECIMALS));

// keep only the fields the nearest-station lookup actually reads
function toStationRecords(stations) {
    return stations
        .filter(station => station.type === 'R')
        .map(station => ({
            id: String(station.id),
            name: station.name,
            state: station.state,
            lat: roundCoordinate(station.lat),
            lng: roundCoordinate(station.lng)
        }))
        .sort((a, b) => a.id.localeCompare(b.id));
}

function renderModule(records) {
    const header = [
        '// Generated by scripts/update-stations.js - do not edit by hand.',
        `// Source: ${MDAPI_URL}`,
        '// NOAA reference (harmonic) stations only; subordinate stations are excluded',
        '// because they serve no 6-minute prediction series.',
        `// ${records.length} station${records.length === 1 ? '' : 's'}.`
    ].join('\n');

    const body = records
        .map(r => `    ${JSON.stringify(r)}`)
        .join(',\n');

    return `${header}\n\nmodule.exports = [\n${body}\n];\n`;
}

async function main() {
    process.stdout.write(`Fetching ${MDAPI_URL}\n`);

    const res = await fetch(MDAPI_URL);
    if (!res.ok) {
        throw new Error(`Station metadata request failed with status: ${res.status}`);
    }

    const { stations } = await res.json();
    if (!Array.isArray(stations) || stations.length === 0) {
        throw new Error('Station metadata response contained no stations');
    }

    const records = toStationRecords(stations);
    if (records.length === 0) {
        throw new Error('No reference stations found - refusing to write an empty station list');
    }

    fs.writeFileSync(OUTPUT_PATH, renderModule(records));
    process.stdout.write(`Wrote ${records.length} reference stations (of ${stations.length}) to ${OUTPUT_PATH}\n`);
}

module.exports = { toStationRecords, renderModule, MDAPI_URL, OUTPUT_PATH };

if (require.main === module) {
    main().catch(err => {
        process.stderr.write(`${err.message}\n`);
        process.exitCode = 1;
    });
}
